import { pathToFileURL } from "node:url";
import fs from "node:fs";
import path from "node:path";
const LIB = "<REPO>/app/lib";
const HERE = "<SESSION>/scratchpad";
const imp = (rel) => import(pathToFileURL(path.join(LIB, rel)).href);
const { traceImage, _internals } = await imp("embroidery/trace/index.js");
const conv = await imp("digitizer/convert.js");
const { refineBoxes, confirmedBoxes } = await imp("embroidery/trace/refine.js");
const item = process.argv[2];
const [set, name] = item.split("/");
const dir = [path.join(HERE, "text/cache", set, name), path.join(HERE, "faces/cache", set, name)].find((d) => fs.existsSync(path.join(d, "image.rgba")));
const meta = JSON.parse(fs.readFileSync(path.join(dir, "meta.json"), "utf8"));
const raw = fs.readFileSync(path.join(dir, "image.rgba"));
const image = { width: meta.width, height: meta.height, data: new Uint8ClampedArray(raw.buffer.slice(raw.byteOffset, raw.byteOffset + raw.length)) };
const mmPerPx = (meta.width / 10) / image.width;
const settings = { ...conv.CONVERT_DEFAULTS, detail: 0.75, people: false, background: "auto" };
const base = { ...conv.traceOptions(settings, mmPerPx), refineLettering: false };
const first = _internals.traceOnce(image, base, null);
const boxes = refineBoxes(first.lettering.blocks, { mmPerPx, width: image.width, height: image.height, origin: first._origin });
const second = _internals.traceOnce(image, base, boxes);
const ok = confirmedBoxes(first.lettering, second, boxes, { mmPerPx });
console.log("first blocks:");
first.lettering.blocks.forEach((b, i) => console.log("  ", i, `L${b.letters}/p${b.count} cap ${b.capMm.toFixed(1)} st ${b.strokeMm.toFixed(2)} colour ${first.palette[b.colors[0]].hex} box [${b.box.map((v) => Math.round(v)).join(",")}]`));
console.log("boxes (block, orig colour, confirmed by the second tracing):", boxes.map((b, i) => `${b.block}:${b.color}:${ok[i]}`).join("  "));
console.log("second blocks:");
second.lettering.blocks.forEach((b, i) => console.log("  ", i, `L${b.letters}/p${b.count} cap ${b.capMm.toFixed(1)} st ${b.strokeMm.toFixed(2)} colour ${second.palette[b.colors[0]].hex} box [${b.box.map((v) => Math.round(v)).join(",")}]`));
